# Python Type Conversion

# Integer to Float
a = 10
b = float(a)
print("Integer to Float:", b)

# Float to Integer
x = 10.8
y = int(x)
print("Float to Integer:", y)

# String to Integer
age = "22"
new_age = int(age)
print("String to Integer:", new_age)

# Integer to String
number = 100
text = str(number)
print("Integer to String:", text)

# Check data types
print(type(b))
print(type(y))
print(type(new_age))
print(type(text))
