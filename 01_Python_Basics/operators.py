# Python Operators

a = 10
b = 5

# Arithmetic Operators
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)

# Comparison Operators
print("Equal:", a == b)
print("Greater:", a > b)
print("Less:", a < b)

# Logical Operators
print("AND:", a > 5 and b < 10)
print("OR:", a < 5 or b < 10)
