# Python Modules

# Importing built-in modules
import math
import random
import datetime

# Math module
number = 25
print("Square Root:", math.sqrt(number))
print("Power:", math.pow(2, 3))

# Random module
print("Random Number:", random.randint(1, 100))

# Datetime module
today = datetime.date.today()
print("Today's Date:", today)
