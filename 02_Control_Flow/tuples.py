# Python Tuples

# Creating a tuple
numbers = (10, 20, 30, 40, 50)

# Display tuple
print("Tuple:", numbers)

# Accessing elements
print("First element:", numbers[0])
print("Last element:", numbers[-1])

# Finding length
print("Length:", len(numbers))

# Loop through tuple
for num in numbers:
    print(num)

# Tuple with different data types
student = ("Brijith", 22, 8.5, True)
print("Student Details:", student)
