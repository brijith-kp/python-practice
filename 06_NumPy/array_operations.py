# NumPy Array Operations

import numpy as np

# Creating two arrays
a = np.array([10, 20, 30, 40])
b = np.array([1, 2, 3, 4])

# Addition
print("Addition:", a + b)

# Subtraction
print("Subtraction:", a - b)

# Multiplication
print("Multiplication:", a * b)

# Division
print("Division:", a / b)

# Power
print("Power:", a ** 2)

# Comparison
print("Greater than 20:", a > 20)

# Sum of arrays
print("Sum:", np.sum(a))

# Mean
print("Mean:", np.mean(a))

# Maximum and Minimum
print("Maximum:", np.max(a))
print("Minimum:", np.min(a))
